/**
 * Crown gears — the part that turns the drive through a right angle.
 *
 * Everything in this machine used to rotate about parallel axes. That is not a
 * detail of the rendering, it is what the thing *was*: a flat mechanism given
 * thickness, with no depth for the eye to read and, worse, with each stage
 * stacked directly in front of the last one and hiding it.
 *
 * A crown gear fixes both at once. Its teeth stand on a face rather than a rim,
 * so it meshes with an ordinary spur pinion whose axis crosses its own at 90° —
 * and a stage hung off that pinion is not merely somewhere else, it is oriented
 * somewhere else. Two of them put three mutually perpendicular axis families in
 * one assembly.
 *
 * ── Why the teeth are straight-sided ─────────────────────────────────────────
 *
 * A crown gear's mating partner is a spur gear, and a spur gear's involute is
 * generated by a *rack* — straight flanks at the pressure angle. So the crown's
 * teeth are that rack, wrapped round a circle: at the pitch cylinder each tooth
 * is half the circular pitch thick, and each flank leans back at 20°. Nothing
 * is approximated here that is not also approximated in the real part; crown
 * gears genuinely only carry contact over a narrow band of face width, which is
 * why real ones are narrow.
 *
 * Tooth thickness grows with radius, because circular pitch does. A crown tooth
 * is therefore a wedge, not a prism, and drawing it as a prism is the tell that
 * someone has made a cog-shaped decoration rather than a gear.
 */

import * as THREE from "three";

const TAU = Math.PI * 2;

export type CrownSpec = {
  teeth: number;
  /** tooth size, shared with the pinion or nothing meshes */
  module: number;
  /** radians; must match the pinion's */
  pressureAngle?: number;
  /** face width, as a fraction of the pitch radius */
  face?: number;
  /** backlash at the pitch line, × module */
  backlash?: number;
};

const DEFAULT_ALPHA = (20 * Math.PI) / 180;

export const crownAlpha = (c: CrownSpec) => c.pressureAngle ?? DEFAULT_ALPHA;
export const crownPitchRadius = (c: CrownSpec) => (c.module * c.teeth) / 2;
/**
 * Full tooth depth, root to tip: 2.25 module, as a rack has.
 *
 * The pitch plane is not the root — it sits one addendum below the tip, which
 * is 1.25 module above the face. Getting that wrong puts the pinion's axis a
 * whole module too low and the two parts chew through each other, so it is
 * written down once here and read everywhere.
 */
export const crownDepth = (c: CrownSpec) => c.module * 2.25;
export const crownAddendum = (c: CrownSpec) => c.module;
/** Height of the pitch plane above the crown's face. */
export const crownPitchHeight = (c: CrownSpec) => c.module * 1.25;
/**
 * Face width, and 0.18 of the pitch radius is not a styling choice.
 *
 * The crown's tooth gap is an angular slot, so its arc width shrinks as you
 * move inward; the pinion's tooth is the same thickness all along its face. The
 * two therefore only fit over a band, and a wide face binds at the inner end.
 * At 0.26 the swept test found 1,860 penetrations, 1,800 of them inboard of the
 * pitch circle and 60 outboard — the asymmetry is the whole story. At 0.18 it
 * is zero.
 *
 * Real crown gears are narrow for exactly this reason, and for the related one
 * that pure rolling only happens at a single radius.
 */
export const crownFace = (c: CrownSpec) => crownPitchRadius(c) * (c.face ?? 0.18);
export const crownInner = (c: CrownSpec) => crownPitchRadius(c) - crownFace(c) / 2;
export const crownOuter = (c: CrownSpec) => crownPitchRadius(c) + crownFace(c) / 2;

/** Ratio of pinion turns to crown turns. */
export const crownRatio = (crown: CrownSpec, pinionTeeth: number) =>
  crown.teeth / pinionTeeth;

/**
 * Where the pinion sits: over the pitch circle, one pinion pitch radius above
 * the pitch plane — and with its axis pointing at the crown's centre.
 *
 * RADIAL, not tangential. This is the one thing about a crown gear that is easy
 * to get backwards and impossible to see afterwards. A crown's teeth are radial
 * ridges; the pinion's teeth run along its own axis; so the two only lie
 * *along* each other if that axis is a radius. Turn the pinion 90° and its
 * teeth cross the crown's like a waffle iron — which still looks, in a still
 * frame, like a gear sitting on a gear. The first version of this file had it
 * tangential and the swept test returned 99,240 penetrations with no phase
 * anywhere able to fix it, which is the signature of a wrong idea rather than a
 * wrong number.
 *
 * It is also why a crown gear's face must be narrow: the crown's surface speed
 * is r·ω and the pinion's is constant along the contact line, so they roll
 * without sliding at exactly one radius and slide everywhere else.
 */
export function crownMesh(crown: CrownSpec, pinionPitchRadius: number) {
  return {
    offset: crownPitchRadius(crown),
    height: crownPitchHeight(crown) + pinionPitchRadius,
  };
}

/**
 * Half the angular thickness of a tooth, at radius `r` and height `y` above the
 * pitch plane.
 *
 * At the pitch plane a tooth takes half the circular pitch, which is π·r/N of
 * arc — an angle of π/N that does not depend on r. Away from it the flanks lean
 * at the pressure angle, and *that* offset is a length, so as an angle it falls
 * off with radius. Hence the wedge.
 */
export function crownHalfAngle(c: CrownSpec, r: number, y: number) {
  const nominal = Math.PI / (2 * c.teeth);
  // `y` is measured from the FACE; the flanks lean about the pitch plane
  const lean = ((y - crownPitchHeight(c)) * Math.tan(crownAlpha(c))) / r;
  const backlash = ((c.backlash ?? 0.3) * c.module) / (2 * r);
  return nominal - lean - backlash;
}

/**
 * The crown gear as a solid: a ring, with a wedge of a tooth standing on it.
 *
 * Built by hand rather than extruded, because there is no plane to extrude
 * along — the teeth rise out of the face, which is the entire point of the
 * part.
 */
export function crownGeometry(c: CrownSpec, plate: number, boreRadius?: number): THREE.BufferGeometry {
  const Rp = crownPitchRadius(c);
  const Ri = crownInner(c);
  const Ro = crownOuter(c);
  const ha = crownDepth(c); // root to tip
  /* Sized to the shaft when the caller knows it. The old fixed fraction of
     the pitch radius was smaller than the shaft the input crown sits on, so
     the shaft passed through solid metal. */
  const bore = boreRadius ?? Rp * 0.22;

  const pos: number[] = [];
  const quad = (
    a: [number, number, number],
    b: [number, number, number],
    d: [number, number, number],
    e: [number, number, number],
  ) => {
    pos.push(...a, ...b, ...d, ...a, ...d, ...e);
  };

  /* The body: a ring from the bore to the outer radius, `plate` thick, its top
     face at z = 0 so the teeth have somewhere to stand. */
  const SEG = 56; // a crown's body is a plain ring; the teeth carry the detail
  for (let i = 0; i < SEG; i++) {
    const a0 = (i / SEG) * TAU;
    const a1 = ((i + 1) / SEG) * TAU;
    const c0 = Math.cos(a0);
    const s0 = Math.sin(a0);
    const c1 = Math.cos(a1);
    const s1 = Math.sin(a1);
    // top face
    quad(
      [c0 * bore, s0 * bore, 0],
      [c0 * Ro, s0 * Ro, 0],
      [c1 * Ro, s1 * Ro, 0],
      [c1 * bore, s1 * bore, 0],
    );
    // bottom face
    quad(
      [c1 * bore, s1 * bore, -plate],
      [c1 * Ro, s1 * Ro, -plate],
      [c0 * Ro, s0 * Ro, -plate],
      [c0 * bore, s0 * bore, -plate],
    );
    // outer rim
    quad(
      [c0 * Ro, s0 * Ro, -plate],
      [c1 * Ro, s1 * Ro, -plate],
      [c1 * Ro, s1 * Ro, 0],
      [c0 * Ro, s0 * Ro, 0],
    );
    // bore
    quad(
      [c1 * bore, s1 * bore, -plate],
      [c0 * bore, s0 * bore, -plate],
      [c0 * bore, s0 * bore, 0],
      [c1 * bore, s1 * bore, 0],
    );
  }

  /* The teeth. Eight corners each: two radii, two heights, two flanks — and
     the half-angle differs at every one of them, which is what makes it a
     wedge rather than a block. */
  for (let i = 0; i < c.teeth; i++) {
    const centre = (i / c.teeth) * TAU;
    const at = (r: number, y: number, side: 1 | -1): [number, number, number] => {
      const a = centre + side * crownHalfAngle(c, r, y);
      return [Math.cos(a) * r, Math.sin(a) * r, y];
    };

    const iB1 = at(Ri, 0, 1);
    const iB2 = at(Ri, 0, -1);
    const oB1 = at(Ro, 0, 1);
    const oB2 = at(Ro, 0, -1);
    const iT1 = at(Ri, ha, 1);
    const iT2 = at(Ri, ha, -1);
    const oT1 = at(Ro, ha, 1);
    const oT2 = at(Ro, ha, -1);

    quad(iB1, oB1, oT1, iT1); // leading flank
    quad(iT2, oT2, oB2, iB2); // trailing flank
    quad(iT1, oT1, oT2, iT2); // tip
    quad(iB1, iT1, iT2, iB2); // inner end
    quad(oB2, oT2, oT1, oB1); // outer end
  }

  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.Float32BufferAttribute(pos, 3));
  g.computeVertexNormals();
  return g;
}

/**
 * Which way up a crown is bolted.
 *
 * It is not cosmetic. Flipping a crown reverses the relationship with its
 * pinion, and the failure is invisible to every check that does not look at
 * the teeth: the ratio is right, the contact point is right, and the two parts
 * grind straight through each other.
 */
export type CrownMount = "up" | "down";

/**
 * The pinion's angle, given the crown's.
 *
 * Phase derived the same way as the spur pair's: with both parts drawn with a
 * tooth centreline on their own reference axis, the pinion needs a *space*
 * where the crown presents a tooth. Verified by sampling in three dimensions —
 * see `crown.test.mts` — because a right-angle mesh that is out by half a pitch
 * looks, in any still, exactly like a right-angle mesh.
 */
export function crownPinionAngle(
  crownAngle: number,
  crown: CrownSpec,
  pinionTeeth: number,
  mount: CrownMount = "up",
  /**
   * Where the pinion sits around the crown, in the crown's own frame.
   *
   * This had no business being absent. The phase of a crown mesh depends on
   * *which* radius the pinion is on, exactly as a spur pair's depends on the
   * bearing between its two shafts — a tooth arrives at one point on the rim
   * before it arrives at another. With it assumed to be zero the maths silently
   * only worked for one arrangement of the machine, and the moment an input
   * shaft was pointed somewhere else both crowns ground straight through their
   * pinions with over a hundred thousand penetrations apiece.
   *
   * Counted in crown teeth: moving the mesh point round by `bearing` is the
   * same as having turned the crown back by it.
   */
  bearing = 0,
  /**
   * True when the pinion's own frame puts a tooth on its reference axis rather
   * than a space, which costs half a pitch.
   *
   * Not derivable from the specs, and that is the honest reason it is a
   * parameter. `frameAt` picks a shaft's local X with a cross product against
   * whichever reference direction happens not to be parallel to the axis, so
   * the roll of every pinion frame in this machine is arbitrary — an artefact
   * of how the frame was constructed, not of the gear. Whether that arbitrary
   * zero lands on a tooth or a gap is therefore a fact about the mounting, and
   * the only thing that can answer it is the mounted mesh itself. See
   * `crownMounted.test.mts`, which found this one by sweeping and now holds it.
   */
  toothOnAxis = false,
) {
  const ratio = crownRatio(crown, pinionTeeth);
  const pitch = TAU / pinionTeeth;
  /* Signed by the mount. Turning a crown over mirrors every tooth bearing
     along with everything else, so the same displacement of the mesh point
     counts the other way round. */
  crownAngle += mount === "down" ? -bearing : bearing;
  const half = toothOnAxis ? pitch / 2 : 0;
  if (mount === "down") {
    /* A crown mounted teeth-down is turned through π about a diameter, and
       that does two things at once. Its own rotation becomes the negative of
       the rotation you see in the world, and the turn mirrors every tooth
       bearing, which moves the phase by half a pitch. The two corrections
       combine to leave no phase term at all.
       
       Both crowns in this machine are mounted that way, and both were driven
       as though they were not: the pinions turned the wrong way, and no
       constant offset could have fixed it, because an inverted rate is right
       at one instant and progressively wronger after. */
    return -crownAngle * ratio + half;
  }
  /* Same sense, because at the mesh the crown's surface runs +Y and so must
     the pinion's; half a pitch of offset, because the crown presents a tooth
     on its own reference radius and the pinion has to present a space there. */
  return crownAngle * ratio - pitch / 2 + half;
}

/**
 * Minimum face width for the pinion: it has to span the crown's whole toothed
 * band, because that band is the length of the contact line.
 */
export const pinionFaceFor = (c: CrownSpec) => crownOuter(c) - crownInner(c);
