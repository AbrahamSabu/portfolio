/*
 * Find and build
 * --------------
 * One command that does the whole thing on your machine:
 *   1. Searches Google Places across a mix of Cork city verticals.
 *   2. Keeps only businesses with NO website (your best leads).
 *   3. Writes them into leads.txt.
 *   4. Runs batch-build.cjs to build a site for each.
 *
 * HOW TO USE
 *   1. Put this file in your project root (same folder as batch-build.cjs and CLAUDE.md).
 *   2. Create a file called google-key.txt in that folder and paste your Google Places key into it.
 *   3. In a terminal in that folder, run:  node find-and-build.js
 *
 * NOTE: this OVERWRITES leads.txt each time it runs.
 */

const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");

// ---- CONFIG (change these when you're ready) -------------------------------

// Keep this LOW for your first runs. Each lead becomes a site that gets built,
// and each build costs money and time. Start at 3, raise it once you trust it.
const MAX_LEADS = 3;

// The mix it searches for in Cork city. Add or remove lines freely.
// Format: [ search query , the "services" label written into leads.txt ]
const VERTICALS = [
  ["landscaping and garden design in Cork city, Ireland", "landscaping and garden design"],
  ["cafe in Cork city, Ireland", "cafe and coffee"],
  ["barber shop in Cork city, Ireland", "barber shop"],
  ["hair salon in Cork city, Ireland", "hair salon"],
  ["electrician in Cork city, Ireland", "electrical services"],
  ["plumber in Cork city, Ireland", "plumbing services"],
];

// Cork city centre, used to keep results local.
const CORK = { latitude: 51.8985, longitude: -8.4756, radius: 8000 };

// ----------------------------------------------------------------------------

const projectRoot = process.cwd();
const keyFile = path.join(projectRoot, "google-key.txt");

if (!fs.existsSync(keyFile)) {
  console.error("No google-key.txt found. Create it in this folder and paste your Google Places key into it.");
  process.exit(1);
}
const API_KEY = fs.readFileSync(keyFile, "utf8").trim();
if (!API_KEY) {
  console.error("google-key.txt is empty. Paste your Google Places key into it.");
  process.exit(1);
}

// Clean a field so it can't break the leads.txt format (no pipes or newlines).
function clean(text) {
  return (text || "").replace(/[|\r\n]+/g, " ").trim();
}

async function search(query) {
  const res = await fetch("https://places.googleapis.com/v1/places:searchText", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Goog-Api-Key": API_KEY,
      "X-Goog-FieldMask":
        "places.displayName,places.formattedAddress,places.nationalPhoneNumber,places.websiteUri,places.regularOpeningHours.weekdayDescriptions,places.googleMapsUri",
    },
    body: JSON.stringify({
      textQuery: query,
      locationBias: { circle: { center: { latitude: CORK.latitude, longitude: CORK.longitude }, radius: CORK.radius } },
    }),
  });

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Places API error (${res.status}): ${body}`);
  }
  const data = await res.json();
  return data.places || [];
}

async function main() {
  console.log("\nSearching Cork city...\n");

  const seen = new Set();
  const leads = [];

  for (const [query, servicesLabel] of VERTICALS) {
    let places = [];
    try {
      places = await search(query);
    } catch (err) {
      console.error(`  Search failed for "${query}": ${err.message}`);
      continue;
    }

    for (const p of places) {
      if (p.websiteUri) continue; // has a website, skip

      const name = clean(p.displayName && p.displayName.text);
      if (!name) continue;

      const dedupeKey = (name + clean(p.formattedAddress)).toLowerCase();
      if (seen.has(dedupeKey)) continue;
      seen.add(dedupeKey);

      const hours = (p.regularOpeningHours && p.regularOpeningHours.weekdayDescriptions
        ? p.regularOpeningHours.weekdayDescriptions.join("; ")
        : "");

      leads.push([
        name,
        servicesLabel,
        clean(p.formattedAddress),
        clean(p.nationalPhoneNumber),
        clean(hours),
        clean(p.googleMapsUri),
        "", // socials: Places doesn't provide these
      ]);
    }
    console.log(`  ${servicesLabel}: ${places.length} found`);
  }

  console.log(`\nNo-website leads found: ${leads.length}`);

  if (leads.length === 0) {
    console.log("Nothing to build. Try different verticals or a wider search.");
    return;
  }

  const chosen = leads.slice(0, MAX_LEADS);
  console.log(`Building the first ${chosen.length} (MAX_LEADS is ${MAX_LEADS}).\n`);

  // Write leads.txt in the format batch-build.cjs expects.
  const header = "# Auto-generated by find-and-build.js. Do not hand-edit; it gets overwritten.\n";
  const body = chosen.map((row) => row.join(" | ")).join("\n");
  fs.writeFileSync(path.join(projectRoot, "leads.txt"), header + body + "\n");

  // Hand off to the batch builder.
  console.log("Handing off to the site builder...\n");
  spawnSync("node", ["batch-build.cjs"], { cwd: projectRoot, shell: true, stdio: "inherit" });
}

main().catch((err) => {
  console.error("\nSomething went wrong:", err.message);
  process.exit(1);
});
